#!/usr/bin/env node
// Writes docs/crm/lists/*.json and README.md from src/crm/schema.ts. The test suite fails if the files are out of date.
// Usage: npm run crm:schemas
import { mkdirSync, writeFileSync } from 'node:fs';
import { CRM_LISTS } from '../../src/crm/schema.ts';
import { schemaHash } from '../../src/schema/lists.ts';

const out = new URL('../../docs/crm/lists/', import.meta.url);
mkdirSync(out, { recursive: true });
export const fileFor = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, '-') + '.json';

for (const l of CRM_LISTS) writeFileSync(new URL(fileFor(l.name), out), JSON.stringify(l, null, 2) + '\n');

const cell = (c) => [
  c.type + (c.multiple ? ' (several)' : ''), c.required ? 'yes' : '', c.lookup ?? '', c.choices ? c.choices.join(', ') : '',
  [c.default ? `default ${c.default}` : '', c.min !== undefined ? `min ${c.min}` : '', c.max !== undefined ? `max ${c.max}` : '', c.indexed ? 'indexed' : ''].filter(Boolean).join(', '),
];
const md = [
  '# CRM list schemas', '',
  `Generated by \`npm run crm:schemas\` from \`src/crm/schema.ts\`. Schema version ${schemaHash(CRM_LISTS)}.`,
  'Every list also has the built-in Title column. System fields are written only by the app or scripts.', '',
  ...CRM_LISTS.flatMap((l) => [
    `## ${l.name}`, '', l.description, '',
    '| Column | Type | Required | Lookup | Choices | Notes |', '| --- | --- | --- | --- | --- | --- |',
    ...l.columns.map((c) => `| ${c.name} | ${cell(c).join(' | ')} |`), '',
  ]),
].join('\n');
writeFileSync(new URL('README.md', out), md);
console.log(`Wrote ${CRM_LISTS.length} schemas and README.md (version ${schemaHash(CRM_LISTS)})`);
